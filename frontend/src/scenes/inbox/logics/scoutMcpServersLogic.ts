export const scoutMcpServersLogic = kea<scoutMcpServersLogicType>([
    path(['scenes', 'inbox', 'logics', 'scoutMcpServersLogic']),
    connect({
        values: [teamLogic, ['currentTeamId'], userLogic, ['user']],
    }),
    actions({
        ensureScoutServerShared: (serverId: string) => ({ serverId }),
        ensureScoutServerSharedComplete: (serverId: string) => ({ serverId }),
    }),
    loaders(({ values }) => ({
        serviceAccounts: [
            [] as MCPServiceAccountApi[],
            {
                loadServiceAccounts: async () => {
                    if (values.currentTeamId === null) {
                        return []
                    }
                    const response = await mcpGatewayServiceAccountsList(String(values.currentTeamId), { limit: 500 })
                    return response.results
                },
            },
        ],
        gatewayServers: [
            [] as MCPGatewayServerApi[],
            {
                loadGatewayServers: async () => {
                    if (values.currentTeamId === null) {
                        return []
                    }
                    const response = await mcpGatewayServersList(String(values.currentTeamId), { limit: 500 })
                    return response.results
                },
            },
        ],
    })),
    reducers({
        serverShareLoadingIds: [
            new Set<string>(),
            {
                ensureScoutServerShared: (state, { serverId }) => new Set(state).add(serverId),
                ensureScoutServerSharedComplete: (state, { serverId }) => {
                    const next = new Set(state)
                    next.delete(serverId)
                    return next
                },
            },
        ],
    }),
    selectors({
        currentUserId: [(s) => [s.user], (user: UserType | null): number | null => user?.id ?? null],
        scoutAccount: [
            (s) => [s.serviceAccounts],
            (serviceAccounts: MCPServiceAccountApi[]): MCPServiceAccountApi | null =>
                serviceAccounts.find((account) => account.agent_key === 'scout') ?? null,
        ],
        scoutServers: [
            (s) => [s.scoutAccount],
            (scoutAccount: MCPServiceAccountApi | null): MCPServiceAccountServerApi[] => [
                ...(scoutAccount?.servers ?? []),
            ],
        ],
        // A grant belongs to one member. A scout run mounts the grants of the person it runs for
        // plus every team-scoped grant in the project, so a teammate's personal grant never backs
        // the viewer's scouts but a teammate's team share does. While the user is still loading
        // neither partition can be attributed, so both stay empty rather than reading the
        // viewer's own grants as teammates'.
        yourScoutServers: [
            (s) => [s.scoutServers, s.currentUserId],
            (scoutServers: MCPServiceAccountServerApi[], currentUserId: number | null): MCPServiceAccountServerApi[] =>
                currentUserId === null ? [] : scoutServers.filter((server) => server.shared_by.id === currentUserId),
        ],
        teammateScoutServers: [
            (s) => [s.scoutServers, s.currentUserId],
            (scoutServers: MCPServiceAccountServerApi[], currentUserId: number | null): MCPServiceAccountServerApi[] =>
                currentUserId === null
                    ? []
                    : scoutServers.filter((server) => server.shared_by.id !== currentUserId && server.scope === 'team'),
        ],
        connectedGatewayServers: [
            (s) => [s.gatewayServers],
            (gatewayServers: MCPGatewayServerApi[]): MCPGatewayServerApi[] =>
                gatewayServers
                    .filter((server) => server.your_connection !== null)
                    .sort((a, b) => a.name.localeCompare(b.name, undefined, { sensitivity: 'base' })),
        ],
        scoutSharedServerIds: [
            (s) => [s.yourScoutServers],
            (yourScoutServers: MCPServiceAccountServerApi[]): Set<string> =>
                new Set(yourScoutServers.map((server) => server.id)),
        ],
        scoutServersLoading: [
            (s) => [s.serviceAccountsLoading],
            (serviceAccountsLoading: boolean): boolean => serviceAccountsLoading,
        ],
    }),
    listeners(({ actions, values }) => ({
        // Selecting a server for a scout also requires the creator's grant on the Scout agent —
        // that grant is what makes the connection mountable at all; the per-scout selection on
        // the config narrows which grants each scout's runs use. Sharing stays personal scope:
        // it backs only this user's scouts.
        ensureScoutServerShared: async ({ serverId }) => {
            const scoutAccount = values.scoutAccount
            const serverName = values.gatewayServers.find((server) => server.id === serverId)?.name ?? 'server'
            if (values.currentTeamId === null || scoutAccount === null || values.scoutSharedServerIds.has(serverId)) {
                actions.ensureScoutServerSharedComplete(serverId)
                return
            }
            try {
                // The response carries the scout account's grants after the change, including who
                // backs each one, which a local merge cannot reconstruct.
                const updatedAccount = await mcpGatewayServiceAccountsAccessCreate(
                    String(values.currentTeamId),
                    scoutAccount.id,
                    { gateway_server_id: serverId, enabled: true, scope: 'personal' }
                )
                actions.loadServiceAccountsSuccess(
                    values.serviceAccounts.map((account) => (account.id === scoutAccount.id ? updatedAccount : account))
                )
            } catch (error: unknown) {
                lemonToast.error(
                    errorDetail(error) ??
                        `Could not share ${serverName} with the Scout agent. This scout can't use it until it's shared.`
                )
            } finally {
                actions.ensureScoutServerSharedComplete(serverId)
            }
        },
    })),
    subscriptions(({ actions }) => ({
        currentTeamId: () => {
            actions.loadServiceAccounts()
            actions.loadGatewayServers()
        },
    })),
])
